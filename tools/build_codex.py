#!/usr/bin/env python3
"""Build the Codex version of the daily-review plugin from the Claude Code sources.

    python3 tools/build_codex.py           # write codex/
    python3 tools/build_codex.py --check   # exit 1 if codex/ is out of date

The Claude Code plugin (skills/, agents/) is the source of truth. Codex reads the same
SKILL.md format, but it doesn't run `!` commands when a skill loads, substitute
${CLAUDE_SKILL_DIR} or $ARGUMENTS, or know Claude's plugin subagents. This script writes
Codex versions of the two skills with those parts rewritten, copies the scripts next to
them, and keeps the Codex plugin manifest at the same version. The review guidance
itself is copied word for word, so both agents review the same way.
"""
import json
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "codex")
NOTE = "<!-- Generated by tools/build_codex.py from the Claude Code skill. Edit the source and rebuild. -->"


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read()


def split_skill(text):
    m = re.match(r"\A---\n(.*?)\n---\n(.*)\Z", text, re.S)
    if not m:
        sys.exit("no frontmatter in a skill or agent file")
    fields = {}
    for line in m.group(1).split("\n"):
        k, _, v = line.partition(":")
        if v.strip():
            fields[k.strip()] = v.strip().strip('"')
    return fields, m.group(2)


def replace(text, old, new, what):
    if text.count(old) != 1:
        sys.exit("build_codex: the source changed and this rewrite no longer applies: %s\n  expected once: %r" % (what, old[:120]))
    return text.replace(old, new)


def slash_to_dollar(text):
    """/daily-review and /review-pr are $daily-review and $review-pr in Codex."""
    return re.sub(r"(?<![\w./-])/(daily-review|review-pr)\b", r"$\1", text)


def guidance(base, with_architecture):
    """daily-review's review guidance ("What this is for" to the end), rewritten for Codex.
    base: how the text names daily-review's skill folder."""
    _, body = split_skill(read("skills/daily-review/SKILL.md"))
    text = body[body.index("## What this is for"):]
    text = replace(
        text,
        "The Scope block lists the commits since the last review, the changed files, the diff file, the sources of truth "
        "and the previous review. If the arguments contain flags (`--days N`, `--since REF`, `--full`, `--rerun`, "
        "`--base BRANCH`, `--architecture`), run `bash ${CLAUDE_SKILL_DIR}/scripts/scope.sh` with those flags and use "
        "its output instead; any other words describe what was built.",
        "The scope lists the commits since the last review, the changed files, the diff file, the sources of truth "
        "and the previous review.",
        "how the scope is produced")
    text = replace(
        text,
        "When this skill comes from the daily-review plugin, the two subagents are named `daily-review:daily-reviewer` "
        "and `daily-review:review-verifier`.",
        "In Codex, spawn them as subagents and give each its instructions, `%s/references/daily-reviewer.md` or "
        "`%s/references/review-verifier.md`, with your brief. Subagents share your sandbox, so tell them not to edit "
        "files. If you can't spawn subagents, do their checks yourself, following the same instructions." % (base, base),
        "subagent names")
    text = text.replace("${CLAUDE_SKILL_DIR}", base)
    if not with_architecture:
        text = re.sub(r"## Weekly architecture review.*?(?=^## )", "", text, flags=re.S | re.M)
    return slash_to_dollar(text)


def daily_review_skill():
    fields, _ = split_skill(read("skills/daily-review/SKILL.md"))
    head = (
        "---\nname: daily-review\ndescription: %s\n---\n%s\n\n# Daily review\n\n"
        "`<skill folder>` below means the folder that holds this SKILL.md; use its full path.\n\n"
        "## Start\n"
        "First run `bash <skill folder>/scripts/scope.sh`, adding any flags from the user's message (`--days N`, "
        "`--since REF`, `--full`, `--rerun`, `--base BRANCH`, `--architecture`). Its output is the scope this skill "
        "refers to; any other words in the message describe what was built.\n\n"
        "The script reads git and writes only to `.reviews/`, so it runs inside Codex's sandbox. It also writes to "
        "`.git` in two cases: on the first run in a repository, to keep `.reviews/` out of git, and when the branch "
        "has merged its base branch, to leave those changes out of the diff. If its warnings show that either failed, "
        "Codex's sandbox (which can keep `.git` read-only) is the likely cause: ask the lead to approve running it "
        "again outside the sandbox.\n\n"
    ) % (json.dumps(slash_to_dollar(fields["description"])), NOTE)
    return head + guidance("<skill folder>", with_architecture=True)


def review_pr_skill():
    fields, body = split_skill(read("skills/review-pr/SKILL.md"))
    text = body[body.index("## What changes for a pull request"):]
    text = replace(
        text,
        "**Fetch the PR.** Run `bash ${CLAUDE_SKILL_DIR}/scripts/pr.sh \"<PR link or number>\"`, adding any `--rerun`, "
        "`--full`, `--clean`, `--since REF` or `--days N` from the arguments.",
        "**Fetch the PR.** Run `bash <skill folder>/scripts/pr.sh \"<PR link or number>\"`, adding any `--rerun`, "
        "`--full`, `--clean`, `--since REF` or `--days N` from the user's message. It calls GitHub and writes to `.git` "
        "(the PR's commits and its worktree), so run it outside Codex's sandbox, with the lead's approval.",
        "fetch step")
    text = replace(
        text,
        "- The scope comes from pr.sh. Where daily-review says to run scope.sh with flags, run pr.sh with them instead.",
        "- The scope comes from pr.sh, which also takes the flags.",
        "where the scope comes from")
    text = replace(
        text,
        "When the arguments include `--dry-run`, stop there and tell the lead where the draft is. Otherwise post with "
        "`python3 ${CLAUDE_SKILL_DIR}/scripts/post_review.py <github_draft>`.",
        "When the user's message includes `--dry-run`, stop there and tell the lead where the draft is. Otherwise post "
        "with `python3 <skill folder>/scripts/post_review.py <github_draft>`, outside the sandbox because it calls "
        "GitHub: the lead's approval of that command is their go-ahead to post.",
        "post step")
    text = replace(
        text,
        "`bash ${CLAUDE_SKILL_DIR}/scripts/pr.sh --clean <number>` removes its worktree",
        "`bash <skill folder>/scripts/pr.sh --clean <number>`, run outside the sandbox, removes its worktree",
        "clean step")
    text = replace(
        text,
        "# From /daily-review\n\n!`bash ${CLAUDE_SKILL_DIR}/scripts/guide.sh`\n",
        "# From $daily-review\n\n" + guidance("<skill folder>/../daily-review", with_architecture=False),
        "daily-review's guidance")
    text = slash_to_dollar(text.replace("${CLAUDE_SKILL_DIR}", "<skill folder>"))
    head = (
        "---\nname: review-pr\ndescription: %s\n---\n%s\n\n# Review a pull request\n\n"
        "`<skill folder>` below means the folder that holds this SKILL.md; use its full path. This skill uses the "
        "daily-review skill installed next to it, in `<skill folder>/../daily-review`.\n\n"
    ) % (json.dumps(slash_to_dollar(fields["description"])), NOTE)
    return head + text


def reference(agent):
    _, body = split_skill(read("agents/%s.md" % agent))
    body = body.replace("the main /daily-review session", "the main review session ($daily-review or $review-pr)")
    body = body.replace("Use Bash only for", "Use the shell only for")
    title = {"daily-reviewer": "daily-reviewer", "review-verifier": "review-verifier"}[agent]
    return "%s\n\n# %s subagent\n\n%s" % (NOTE, title, slash_to_dollar(body).lstrip("\n"))


OPENAI_YAML = {
    "daily-review": (
        "interface:\n"
        "  display_name: \"Daily review\"\n"
        "  short_description: \"Review your team's latest commits against your plan and docs\"\n"
        "policy:\n"
        "  allow_implicit_invocation: false\n"),
    "review-pr": (
        "interface:\n"
        "  display_name: \"Review a pull request\"\n"
        "  short_description: \"Review a GitHub PR and post it as a pending review\"\n"
        "policy:\n"
        "  allow_implicit_invocation: false\n"),
}


def plugin_json():
    claude = json.loads(read(".claude-plugin/plugin.json"))
    manifest = {
        "$schema": "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json",
        "name": claude["name"],
        "version": claude["version"],
        "description": ("Code review for tech leads, against your plan and architecture docs. $daily-review reviews your "
                        "team's latest commits; $review-pr reviews a GitHub pull request and posts it as a pending "
                        "review you submit. Reports only what is worth fixing."),
        "author": {"name": claude["author"]["name"], "url": "https://github.com/z4forzubair"},
        "homepage": claude["repository"],
        "repository": claude["repository"],
        "license": claude["license"],
        "keywords": claude["keywords"] + ["codex"],
    }
    return json.dumps(manifest, indent=2) + "\n"


def expected():
    """Every file under codex/: path -> bytes."""
    files = {
        "plugin.json": plugin_json(),
        "skills/daily-review/SKILL.md": daily_review_skill(),
        "skills/daily-review/agents/openai.yaml": OPENAI_YAML["daily-review"],
        "skills/daily-review/references/daily-reviewer.md": reference("daily-reviewer"),
        "skills/daily-review/references/review-verifier.md": reference("review-verifier"),
        "skills/review-pr/SKILL.md": review_pr_skill(),
        "skills/review-pr/agents/openai.yaml": OPENAI_YAML["review-pr"],
    }
    files = {k: v.encode("utf-8") for k, v in files.items()}
    for src, dst in [
        ("skills/daily-review/scripts/scope.sh", "skills/daily-review/scripts/scope.sh"),
        ("skills/daily-review/scripts/docx2md.py", "skills/daily-review/scripts/docx2md.py"),
        ("skills/daily-review/templates/REVIEW.template.md", "skills/daily-review/templates/REVIEW.template.md"),
        ("skills/review-pr/scripts/pr.sh", "skills/review-pr/scripts/pr.sh"),
        ("skills/review-pr/scripts/post_review.py", "skills/review-pr/scripts/post_review.py"),
    ]:
        with open(os.path.join(ROOT, src), "rb") as f:
            files[dst] = f.read()
    for name, data in files.items():
        if name.endswith(".md") and (b"${CLAUDE_SKILL_DIR}" in data or b"$ARGUMENTS" in data or b"!`" in data
                                     or b"daily-review:" in data):
            sys.exit("build_codex: Claude-only syntax left in codex/%s" % name)
    return files


def on_disk():
    found = {}
    for d, _, names in os.walk(OUT):
        for n in names:
            if n.endswith(".pyc"):
                continue
            p = os.path.join(d, n)
            with open(p, "rb") as f:
                found[os.path.relpath(p, OUT)] = f.read()
    return found


def main():
    want = expected()
    if "--check" in sys.argv[1:]:
        have = on_disk()
        stale = sorted(set(want) ^ set(have) | {k for k in want if k in have and want[k] != have[k]})
        if stale:
            print("codex/ is out of date. Run: python3 tools/build_codex.py")
            for k in stale:
                print("  codex/" + k)
            return 1
        print("codex/ is up to date")
        return 0
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    for name, data in sorted(want.items()):
        path = os.path.join(OUT, name)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as f:
            f.write(data)
    print("wrote codex/ (%d files)" % len(want))
    return 0


if __name__ == "__main__":
    sys.exit(main())
