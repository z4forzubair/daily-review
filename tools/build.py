#!/usr/bin/env python3
"""Build the Codex and Cursor versions of the daily-review plugin from the Claude Code sources.

    python3 tools/build.py           # write codex/ and cursor/
    python3 tools/build.py --check   # exit 1 if either is out of date

The Claude Code plugin (skills/, agents/) is the source of truth. Codex and Cursor read
the same SKILL.md format, but they don't run `!` commands when a skill loads, substitute
${CLAUDE_SKILL_DIR} or $ARGUMENTS, or know Claude's plugin subagents. This script writes
each agent's version of the two skills with those parts rewritten, copies the scripts next
to them, and keeps the plugin manifests at the same version. The review guidance itself is
copied word for word, so every agent reviews the same way.
"""
import json
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NOTE = "<!-- Generated by tools/build.py from the Claude Code plugin. Edit the source and rebuild. -->"

TARGETS = {
    "codex": {
        "name": "Codex",
        "invoke": "$",
        "frontmatter": "",
        "start_note": (
            "The script reads git and writes only to `.reviews/`, so it runs inside Codex's sandbox. It also writes to "
            "`.git` in two cases: on the first run in a repository, to keep `.reviews/` out of git, and when the branch "
            "has merged its base branch, to leave those changes out of the diff. If its warnings show that either failed, "
            "Codex's sandbox (which can keep `.git` read-only) is the likely cause: ask the lead to approve running it "
            "again outside the sandbox."),
        "fetch_note": ("It calls GitHub and writes to `.git` (the PR's commits and its worktree), so run it outside "
                       "Codex's sandbox, with the lead's approval."),
        "post_tail": (", outside the sandbox because it calls GitHub: the lead's approval of that command is their "
                      "go-ahead to post."),
        "clean": "`bash <skill folder>/scripts/pr.sh --clean <number>`, run outside the sandbox, removes its worktree",
        "subagents": (
            "In Codex, spawn them as subagents and give each its instructions, `{base}/references/daily-reviewer.md` or "
            "`{base}/references/review-verifier.md`, with your brief. Subagents share your sandbox, so tell them not to "
            "edit files. If you can't spawn subagents, do their checks yourself, following the same instructions."),
    },
    "cursor": {
        "name": "Cursor",
        "invoke": "/",
        "frontmatter": "disable-model-invocation: true\n",
        "start_note": (
            "If Cursor runs it in its sandbox and it fails on a restriction, run it again outside the sandbox."),
        "fetch_note": ("It calls GitHub and writes to `.git` (the PR's commits and its worktree): if Cursor's sandbox "
                       "blocks that, run it outside the sandbox."),
        "post_tail": ". It calls GitHub, so it may also need to run outside Cursor's sandbox.",
        "clean": "`bash <skill folder>/scripts/pr.sh --clean <number>` removes its worktree",
        "subagents": (
            "In Cursor, use the `daily-reviewer` and `review-verifier` subagents that come with this plugin, with your "
            "brief. If they aren't installed, give a subagent the instructions in `{base}/references/daily-reviewer.md` "
            "or `{base}/references/review-verifier.md` instead, or do their checks yourself."),
    },
}


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read()


def split_skill(text):
    m = re.match(r"\A---\n(.*?)\n---\n(.*)\Z", text, re.S)
    if not m:
        sys.exit("build: no frontmatter in a skill or agent file")
    fields = {}
    for line in m.group(1).split("\n"):
        k, _, v = line.partition(":")
        if v.strip():
            fields[k.strip()] = v.strip().strip('"')
    return fields, m.group(2)


def replace(text, old, new, what):
    if text.count(old) != 1:
        sys.exit("build: the source changed and this rewrite no longer applies: %s\n  expected once: %r" % (what, old[:120]))
    return text.replace(old, new)


def invoke(text, t):
    """Skills are /daily-review and /review-pr in Claude Code and Cursor, $daily-review and $review-pr in Codex."""
    if t["invoke"] == "/":
        return text
    return re.sub(r"(?<![\w./-])/(daily-review|review-pr)\b", t["invoke"] + r"\1", text)


def guidance(t, base, with_architecture):
    """daily-review's review guidance ("What this is for" to the end), rewritten for the target agent.
    base: how the text names daily-review's skill folder."""
    _, body = split_skill(read("skills/daily-review/SKILL.md"))
    text = body[body.index("## What this is for"):]
    text = replace(
        text,
        "The Scope block lists the commits since the last review, the changed files, the diff file, the sources of truth "
        "and the previous review. If the arguments contain flags (`--days N`, `--since REF`, `--full`, `--rerun`, "
        "`--base BRANCH`, `--architecture`), run `bash ${CLAUDE_SKILL_DIR}/scripts/scope.sh` with those flags and use "
        "its output instead; any other words describe what was built.",
        "The scope lists the commits since the last review, the changed files, the diff file, the sources of truth "
        "and the previous review.",
        "how the scope is produced")
    text = replace(
        text,
        "When this skill comes from the daily-review plugin, the two subagents are named `daily-review:daily-reviewer` "
        "and `daily-review:review-verifier`.",
        t["subagents"].format(base=base),
        "subagent names")
    text = text.replace("${CLAUDE_SKILL_DIR}", base)
    if not with_architecture:
        text = re.sub(r"## Weekly architecture review.*?(?=^## )", "", text, flags=re.S | re.M)
    return invoke(text, t)


def frontmatter(t, name, description):
    return "---\nname: %s\ndescription: %s\n%s---\n%s\n\n" % (name, json.dumps(invoke(description, t)), t["frontmatter"], NOTE)


def daily_review_skill(t):
    fields, _ = split_skill(read("skills/daily-review/SKILL.md"))
    head = frontmatter(t, "daily-review", fields["description"]) + (
        "# Daily review\n\n"
        "`<skill folder>` below means the folder that holds this SKILL.md; use its full path.\n\n"
        "## Start\n"
        "First run `bash <skill folder>/scripts/scope.sh`, adding any flags from the user's message (`--days N`, "
        "`--since REF`, `--full`, `--rerun`, `--base BRANCH`, `--architecture`). Its output is the scope this skill "
        "refers to; any other words in the message describe what was built.\n\n"
        "%s\n\n") % t["start_note"]
    return head + guidance(t, "<skill folder>", with_architecture=True)


def review_pr_skill(t):
    fields, body = split_skill(read("skills/review-pr/SKILL.md"))
    text = body[body.index("## What changes for a pull request"):]
    text = replace(
        text,
        "**Fetch the PR.** Run `bash ${CLAUDE_SKILL_DIR}/scripts/pr.sh \"<PR link or number>\"`, adding any `--rerun`, "
        "`--full`, `--clean`, `--since REF` or `--days N` from the arguments.",
        "**Fetch the PR.** Run `bash <skill folder>/scripts/pr.sh \"<PR link or number>\"`, adding any `--rerun`, "
        "`--full`, `--clean`, `--since REF` or `--days N` from the user's message. " + t["fetch_note"],
        "fetch step")
    text = replace(
        text,
        "- The scope comes from pr.sh. Where daily-review says to run scope.sh with flags, run pr.sh with them instead.",
        "- The scope comes from pr.sh, which also takes the flags.",
        "where the scope comes from")
    text = replace(
        text,
        "When the arguments include `--dry-run`, stop there and tell the lead where the draft is. Otherwise post with "
        "`python3 ${CLAUDE_SKILL_DIR}/scripts/post_review.py <github_draft>`.",
        "When the user's message includes `--dry-run`, stop there and tell the lead where the draft is. Otherwise post "
        "with `python3 <skill folder>/scripts/post_review.py <github_draft>`" + t["post_tail"],
        "post step")
    text = replace(
        text,
        "`bash ${CLAUDE_SKILL_DIR}/scripts/pr.sh --clean <number>` removes its worktree",
        t["clean"],
        "clean step")
    text = replace(
        text,
        "# From /daily-review\n\n!`bash ${CLAUDE_SKILL_DIR}/scripts/guide.sh`\n",
        "# From /daily-review\n\n" + guidance(t, "<skill folder>/../daily-review", with_architecture=False),
        "daily-review's guidance")
    text = invoke(text.replace("${CLAUDE_SKILL_DIR}", "<skill folder>"), t)
    head = frontmatter(t, "review-pr", fields["description"]) + (
        "# Review a pull request\n\n"
        "`<skill folder>` below means the folder that holds this SKILL.md; use its full path. This skill uses the "
        "daily-review skill installed next to it, in `<skill folder>/../daily-review`.\n\n")
    return head + text


def agent_body(t, agent):
    fields, body = split_skill(read("agents/%s.md" % agent))
    body = body.replace("the main /daily-review session", "the main review session (/daily-review or /review-pr)")
    body = body.replace("Use Bash only for", "Use the shell only for")
    return fields, invoke(body, t).lstrip("\n")


def reference(t, agent):
    _, body = agent_body(t, agent)
    return "%s\n\n# %s subagent\n\n%s" % (NOTE, agent, body)


def cursor_agent(t, agent):
    """A Cursor subagent: read-only, on the parent's model."""
    fields, body = agent_body(t, agent)
    return "---\nname: %s\ndescription: %s\nmodel: inherit\nreadonly: true\n---\n%s\n\n%s" % (
        agent, json.dumps(fields["description"]), NOTE, body)


OPENAI_YAML = {
    "daily-review": (
        "interface:\n"
        "  display_name: \"Daily review\"\n"
        "  short_description: \"Review your team's latest commits against your plan and docs\"\n"
        "policy:\n"
        "  allow_implicit_invocation: false\n"),
    "review-pr": (
        "interface:\n"
        "  display_name: \"Review a pull request\"\n"
        "  short_description: \"Review a GitHub PR and post it as a pending review\"\n"
        "policy:\n"
        "  allow_implicit_invocation: false\n"),
}


def manifest(t):
    claude = json.loads(read(".claude-plugin/plugin.json"))
    p = t["invoke"]
    data = {
        "name": claude["name"],
        "version": claude["version"],
        "description": ("Code review for tech leads, against your plan and architecture docs. %sdaily-review reviews your "
                        "team's latest commits; %sreview-pr reviews a GitHub pull request and posts it as a pending "
                        "review you submit. Reports only what is worth fixing." % (p, p)),
        "author": {"name": claude["author"]["name"]},
        "homepage": claude["repository"],
        "repository": claude["repository"],
        "license": claude["license"],
        "keywords": [k for k in claude["keywords"] if k not in ("codex", "cursor")] + [t["name"].lower()],
    }
    if t is TARGETS["codex"]:
        data = dict([("$schema", "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json")] + list(data.items()))
        data["author"]["url"] = "https://github.com/z4forzubair"
    return json.dumps(data, indent=2) + "\n"


def expected(key):
    """Every file the target's folder should hold: path -> bytes."""
    t = TARGETS[key]
    files = {
        "skills/daily-review/SKILL.md": daily_review_skill(t),
        "skills/daily-review/references/daily-reviewer.md": reference(t, "daily-reviewer"),
        "skills/daily-review/references/review-verifier.md": reference(t, "review-verifier"),
        "skills/review-pr/SKILL.md": review_pr_skill(t),
    }
    if key == "codex":
        files["plugin.json"] = manifest(t)
        files["skills/daily-review/agents/openai.yaml"] = OPENAI_YAML["daily-review"]
        files["skills/review-pr/agents/openai.yaml"] = OPENAI_YAML["review-pr"]
    else:
        files[".cursor-plugin/plugin.json"] = manifest(t)
        files["agents/daily-reviewer.md"] = cursor_agent(t, "daily-reviewer")
        files["agents/review-verifier.md"] = cursor_agent(t, "review-verifier")
    files = {k: v.encode("utf-8") for k, v in files.items()}
    for path in ["skills/daily-review/scripts/scope.sh", "skills/daily-review/scripts/docx2md.py",
                 "skills/daily-review/templates/REVIEW.template.md", "skills/review-pr/scripts/pr.sh",
                 "skills/review-pr/scripts/post_review.py"]:
        with open(os.path.join(ROOT, path), "rb") as f:
            files[path] = f.read()
    other = [v["name"] for k, v in TARGETS.items() if k != key]
    for name, data in files.items():
        if not name.endswith(".md"):
            continue
        for bad in [b"${CLAUDE_SKILL_DIR}", b"$ARGUMENTS", b"!`", b"daily-review:"] + [o.encode() + b"'s sandbox" for o in other]:
            if bad in data:
                sys.exit("build: %r left in %s/%s" % (bad.decode(), key, name))
    return files


def on_disk(out):
    found = {}
    for d, _, names in os.walk(out):
        for n in names:
            if n.endswith(".pyc"):
                continue
            p = os.path.join(d, n)
            with open(p, "rb") as f:
                found[os.path.relpath(p, out)] = f.read()
    return found


def main():
    check = "--check" in sys.argv[1:]
    status = 0
    for key in TARGETS:
        want, out = expected(key), os.path.join(ROOT, key)
        if check:
            have = on_disk(out)
            stale = sorted(set(want) ^ set(have) | {k for k in want if k in have and want[k] != have[k]})
            if stale:
                print("%s/ is out of date. Run: python3 tools/build.py" % key)
                for k in stale:
                    print("  %s/%s" % (key, k))
                status = 1
            else:
                print("%s/ is up to date" % key)
            continue
        if os.path.isdir(out):
            shutil.rmtree(out)
        for name, data in sorted(want.items()):
            path = os.path.join(out, name)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "wb") as f:
                f.write(data)
        print("wrote %s/ (%d files)" % (key, len(want)))
    return status


if __name__ == "__main__":
    sys.exit(main())
